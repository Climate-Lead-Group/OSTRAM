"""Declared restriction-materialization prerequisites.

A registry may declare that one root's Restrictions rows are generated by
another root (``{"type": "restrictions", "scenario": ...}``).  The declared
prerequisite widens A3 materialization and snapshot checking only; the
downstream B1/B2/reporting selection stays exactly what the user requested.
"""

